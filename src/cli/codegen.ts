import { existsSync, readFileSync } from 'fs';
import { mkdir, readFile, writeFile } from 'fs/promises';
import { join } from 'path';

import { CURATED_CATALOG } from '../shared/catalog';
import type { CuratedPlugin } from '../shared/definitions';

import type { CliContext } from './context';
import { logInfo } from './log';

/**
 * A curated plugin is "enabled" when the app depends on the matching
 * Capacitor plugin. Detection is a static scan of the app's dependencies,
 * mirroring the Electron platform's sync-time discovery.
 */
const CAPACITOR_PACKAGE_BY_PLUGIN: Record<string, string> = {
  Filesystem: '@capacitor/filesystem',
  Preferences: '@capacitor/preferences',
  Dialog: '@capacitor/dialog',
  LocalNotifications: '@capacitor/local-notifications',
};

export async function generateCapabilities(context: CliContext): Promise<void> {
  const enabled = detectEnabledPlugins(context);
  await writeCapabilityFile(context, enabled);
  await writeCargoManifest(context, enabled);
  logInfo(
    `Enabled ${enabled.length} curated plugin(s): ${
      enabled.map(plugin => plugin.name).join(', ') || '(none)'
    }.`,
  );
}

/**
 * Writes `src-tauri/src/generated.rs` — the per-app registrar that the thin
 * `main.rs` calls. Regenerated on every sync; not user-owned.
 */
export async function generateRustGlue(context: CliContext): Promise<void> {
  const enabled = detectEnabledPlugins(context);
  const registrations = pluginRegistrations(enabled)
    .map(line => `        ${line}`)
    .join('\n');
  const body = [
    '// Generated by @capawesome/capacitor-tauri — do not edit.',
    'use tauri::{Builder, Wry};',
    '',
    '#[allow(unused_mut)]',
    'pub fn register_plugins(builder: Builder<Wry>) -> Builder<Wry> {',
    '    builder',
    registrations,
    '}',
    '',
  ].join('\n');
  await writeFile(join(context.tauriDir, 'src', 'generated.rs'), body);
}

function detectEnabledPlugins(context: CliContext): CuratedPlugin[] {
  const packageJson = JSON.parse(
    readFileSync(join(context.rootDir, 'package.json'), 'utf8'),
  ) as { dependencies?: Record<string, string> };
  const dependencies = new Set(Object.keys(packageJson.dependencies ?? {}));
  return CURATED_CATALOG.filter(plugin =>
    dependencies.has(CAPACITOR_PACKAGE_BY_PLUGIN[plugin.name]),
  );
}

/**
 * Generates `src-tauri/capabilities/capacitor.json`: deny-by-default, with
 * only the permissions required by the enabled curated plugins. The default
 * window label in Tauri scaffolds is `main`.
 */
async function writeCapabilityFile(
  context: CliContext,
  enabled: CuratedPlugin[],
): Promise<void> {
  const capabilitiesDir = join(context.tauriDir, 'capabilities');
  await mkdir(capabilitiesDir, { recursive: true });
  const permissions = [
    'core:default',
    ...enabled.flatMap(plugin => plugin.capabilities),
  ];
  const capability = {
    $schema: '../gen/schemas/desktop-schema.json',
    identifier: 'capacitor',
    description:
      'Generated by @capawesome/capacitor-tauri — do not edit. Grants the minimum permissions for the enabled Capacitor plugins.',
    windows: ['main'],
    permissions,
  };
  await writeFile(
    join(capabilitiesDir, 'capacitor.json'),
    `${JSON.stringify(capability, null, 2)}\n`,
  );
}

/**
 * Rewrites the managed dependency block in `src-tauri/Cargo.toml` between
 * marker comments, so only the crates for enabled plugins are compiled in.
 */
async function writeCargoManifest(
  context: CliContext,
  enabled: CuratedPlugin[],
): Promise<void> {
  const cargoPath = join(context.tauriDir, 'Cargo.toml');
  if (!existsSync(cargoPath)) {
    return;
  }
  const begin = '# capacitor:plugins:begin';
  const end = '# capacitor:plugins:end';
  const block = [
    begin,
    ...enabled.map(
      plugin =>
        `${plugin.crate.replace(/^tauri-plugin-/, 'tauri-plugin-')} = "${plugin.crateVersion}"`,
    ),
    end,
  ].join('\n');
  const original = await readFile(cargoPath, 'utf8');
  const pattern = new RegExp(`${begin}[\\s\\S]*?${end}`);
  const updated = pattern.test(original)
    ? original.replace(pattern, block)
    : `${original.trimEnd()}\n\n${block}\n`;
  await writeFile(cargoPath, updated);
}

/**
 * Returns the registration lines for enabled plugin crates, injected into
 * the generated Rust glue.
 */
export function pluginRegistrations(enabled: CuratedPlugin[]): string[] {
  return enabled.map(plugin => {
    const crateIdent = plugin.crate.replace(/-/g, '_');
    const initializer =
      plugin.crate === 'tauri-plugin-store'
        ? `${crateIdent}::Builder::new().build()`
        : `${crateIdent}::init()`;
    return `.plugin(${initializer})`;
  });
}
